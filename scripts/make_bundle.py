def _gather_source_tree(staging: Path) -> list[Path]:
    """Copy source files/dirs into staging/source/ and return the list of files created."""
    src_out = staging / "source"
    src_out.mkdir(parents=True, exist_ok=True)

    copied: list[Path] = []

    for name in SOURCE_FILES:
        src = PROJECT_ROOT / name
        if not src.is_file():
            raise SystemExit(f"Missing source file: {src}")
        dst = src_out / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        copied.append(dst)

    for dirname in SOURCE_DIRS:
        src = PROJECT_ROOT / dirname
        if not src.is_dir():
            raise SystemExit(f"Missing source dir: {src}")
        for child in src.rglob("*"):
            if child.is_dir():
                continue
            if "__pycache__" in child.parts or child.suffix in {".pyc", ".pyo"}:
                continue
            rel = child.relative_to(PROJECT_ROOT)
            dst = src_out / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(child, dst)
            copied.append(dst)

    return copied


def _copy_data_artifacts(staging: Path) -> list[Path]:
    """Copy memory.db and the GGUF model into staging/data/."""
    copied: list[Path] = []

    memory_db = PROJECT_ROOT / "data" / "memory.db"
    if not memory_db.is_file():
        raise SystemExit(
            f"data/memory.db not found. Run ingest.py on the Mac first: "
            f"NOTES_DIR=<your-notes> uv run python ingest.py"
        )
    dst = staging / "data" / "memory.db"
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(memory_db, dst)
    copied.append(dst)

    models_src = PROJECT_ROOT / "data" / "models"
    ggufs = sorted(models_src.glob("*.gguf"))
    if not ggufs:
        raise SystemExit(
            f"No .gguf model in {models_src}. Run setup/download_model.py first."
        )
    for gguf in ggufs:
        dst = staging / "data" / "models" / gguf.name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(gguf, dst)
        copied.append(dst)

    return copied


def _download_windows_extensions(staging: Path) -> list[Path]:
    """Fetch Windows vector.dll + memory.dll from GitHub Releases into staging/data/extensions/."""
    ext_dir = staging / "data" / "extensions"
    ext_dir.mkdir(parents=True, exist_ok=True)

    key = ("windows", "x86_64")
    copied: list[Path] = []
    with tempfile.TemporaryDirectory() as tmp_str:
        tmp = Path(tmp_str)

        vector_url = VECTOR_URL_TEMPLATE.format(version=VECTOR_VERSION, asset=VECTOR_ASSETS[key])
        vector_archive = tmp / VECTOR_ASSETS[key]
        stream_download(vector_url, vector_archive, timeout=120.0)
        vector_dll = ext_dir / "vector.dll"
        _extract_from_tar_gz(vector_archive, ".dll", vector_dll)
        copied.append(vector_dll)

        memory_url = MEMORY_URL_TEMPLATE.format(version=MEMORY_VERSION, asset=MEMORY_ASSETS[key])
        memory_archive = tmp / MEMORY_ASSETS[key]
        stream_download(memory_url, memory_archive, timeout=120.0)
        memory_dll = ext_dir / "memory.dll"
        _extract_from_tar_gz(memory_archive, ".dll", memory_dll)
        copied.append(memory_dll)

    return copied


def _download_portable_uv(staging: Path, uv_version: str) -> Path:
    """Fetch uv.exe for Windows into staging/bin/uv.exe."""
    bin_dir = staging / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp_str:
        tmp = Path(tmp_str)
        url = UV_URL_TEMPLATE.format(version=uv_version, asset=UV_ASSET)
        archive = tmp / UV_ASSET
        stream_download(url, archive, timeout=120.0)
        uv_exe = bin_dir / "uv.exe"
        _extract_uv_exe(archive, uv_exe)
    return uv_exe


def _write_installers_and_readme(staging: Path) -> list[Path]:
    files: list[Path] = []

    ps1 = staging / "install.ps1"
    ps1.write_text(INSTALL_PS1, encoding="utf-8")
    files.append(ps1)

    # Write install.bat with CRLF line endings for Windows friendliness.
    bat = staging / "install.bat"
    bat.write_bytes(INSTALL_BAT.replace("\n", "\r\n").encode("utf-8"))
    files.append(bat)

    readme = staging / "README-windows.md"
    readme.write_text(README_WINDOWS, encoding="utf-8")
    files.append(readme)

    return files


def _build_manifest(staging: Path, bundle_name: str, uv_version: str) -> Path:
    entries = []
    for path in sorted(staging.rglob("*")):
        if path.is_dir():
            continue
        if path.name == "manifest.json":
            continue
        rel = path.relative_to(staging).as_posix()
        entries.append(
            {
                "path": rel,
                "size": path.stat().st_size,
                "sha256": _sha256(path),
            }
        )
    manifest = {
        "bundle": bundle_name,
        "generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        "uv_version": uv_version,
        "sqlite_vector_version": VECTOR_VERSION,
        "sqlite_memory_version": MEMORY_VERSION,
        "files": entries,
    }
    out = staging / "manifest.json"
    out.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return out


def _zip_bundle(staging: Path, bundle_name: str, out_zip: Path) -> None:
    """Write staging/ into out_zip, nested under bundle_name/ as the top-level folder."""
    out_zip.parent.mkdir(parents=True, exist_ok=True)
    # allowZip64=True — the GGUF alone is 600 MB, total bundle easily fits in standard ZIP32
    # but larger datasets could push over 4 GB, so keep it safe.
    with zipfile.ZipFile(out_zip, "w", allowZip64=True) as zf:
        for path in sorted(staging.rglob("*")):
            if path.is_dir():
                continue
            rel = path.relative_to(staging).as_posix()
            arcname = f"{bundle_name}/{rel}"
            compression = _compression_for(rel)
            size_mb = path.stat().st_size / (1024 * 1024)
            print(
                f"  add {arcname} ({size_mb:.1f} MB, "
                f"{'DEFLATE' if compression == zipfile.ZIP_DEFLATED else 'STORED'})",
                file=sys.stderr,
            )
            zf.write(path, arcname=arcname, compress_type=compression)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build a Windows distribution bundle")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DIST_DIR,
        help="Where to write the .zip (default: <project>/dist)",
    )
    parser.add_argument(
        "--uv-version",
        default=DEFAULT_UV_VERSION,
        help=f"Portable uv version to bundle (default: {DEFAULT_UV_VERSION})",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite an existing bundle zip with the same timestamped name",
    )
    args = parser.parse_args()

    bundle_name = "rag-bundle-" + datetime.now().strftime("%Y-%m-%d-%H%M")
    out_zip = args.output_dir / f"{bundle_name}.zip"

    if out_zip.exists() and not args.force:
        raise SystemExit(f"{out_zip} already exists. Re-run with --force to overwrite.")

    print(f"Building bundle: {bundle_name}", file=sys.stderr)
    print(f"Output:         {out_zip}", file=sys.stderr)
    print(f"uv version:     {args.uv_version}", file=sys.stderr)
    print("", file=sys.stderr)

    with tempfile.TemporaryDirectory(prefix="rag-bundle-") as staging_str:
        staging = Path(staging_str)

        print("Step 1/6: copying source tree...", file=sys.stderr)
        _gather_source_tree(staging)

        print("Step 2/6: copying data artifacts (memory.db + GGUF)...", file=sys.stderr)
        _copy_data_artifacts(staging)

        print("Step 3/6: downloading Windows extensions (vector.dll + memory.dll)...", file=sys.stderr)
        _download_windows_extensions(staging)

        print(f"Step 4/6: downloading portable uv {args.uv_version}...", file=sys.stderr)
        _download_portable_uv(staging, args.uv_version)

        print("Step 5/6: writing installers and README...", file=sys.stderr)
        _write_installers_and_readme(staging)

        print("Step 6/6: building manifest + zipping...", file=sys.stderr)
        _build_manifest(staging, bundle_name, args.uv_version)

        _zip_bundle(staging, bundle_name, out_zip)

    size_mb = out_zip.stat().st_size / (1024 * 1024)
    print("", file=sys.stderr)
    print(f"Bundle ready: {out_zip} ({size_mb:.1f} MB)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
