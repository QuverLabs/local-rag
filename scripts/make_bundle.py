r"""Build a self-contained Windows distribution bundle (ZIP) of the RAG project.

Run on macOS after a successful ingest. The resulting ZIP contains:

    rag-bundle-YYYY-MM-DD-HHMM/
      source/                           # server.py, ingest.py, setup/, pyproject.toml, uv.lock, ...
      data/
        memory.db                       # copied from <project>/data/memory.db
        models/*.gguf                   # copied from <project>/data/models/
        extensions/{vector,memory}.dll  # downloaded fresh for Windows
      bin/
        uv.exe                          # portable uv for Windows (no install needed)
      install.ps1
      install.bat
      README-windows.md
      manifest.json                     # SHA256 of every file

The user runs `install.bat` on Windows — it unpacks deps into a local `.venv`
via the bundled uv.exe, writes `.env` with bundle-absolute paths, and
auto-registers the MCP server in `%APPDATA%\Claude\claude_desktop_config.json`.

No admin rights, no external downloads, no PATH mutation.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
import tarfile
import tempfile
import zipfile
from datetime import datetime, timezone
from pathlib import Path

from setup._http import stream_download
from setup.download_extensions import (
    MEMORY_ASSETS,
    MEMORY_URL_TEMPLATE,
    MEMORY_VERSION,
    VECTOR_ASSETS,
    VECTOR_URL_TEMPLATE,
    VECTOR_VERSION,
)


DEFAULT_UV_VERSION = "0.11.7"
UV_ASSET = "uv-x86_64-pc-windows-msvc.zip"
UV_URL_TEMPLATE = "https://github.com/astral-sh/uv/releases/download/{version}/{asset}"

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DIST_DIR = PROJECT_ROOT / "dist"

# Files/dirs copied verbatim from <project>/ into bundle/source/.
SOURCE_FILES = [
    "server.py",
    "ingest.py",
    "pyproject.toml",
    "uv.lock",
    ".env.example",
    "claude_desktop_config.example.json",
    "README.md",
]
SOURCE_DIRS = ["setup"]


# ---------------------------------------------------------------------------
# Installer + README templates (embedded so the bundle is self-contained).
# ---------------------------------------------------------------------------

INSTALL_PS1 = r"""# install.ps1 - unpack the RAG bundle on Windows.
# Run from the unzipped bundle folder (double-click install.bat, or right-click -> Run with PowerShell).

$ErrorActionPreference = "Stop"
$BundleRoot = $PSScriptRoot
Set-Location $BundleRoot

Write-Host ""
Write-Host "=== local-rag Windows installer ==="
Write-Host "Bundle root: $BundleRoot"
Write-Host ""

$UvExe = Join-Path $BundleRoot "bin\uv.exe"
if (-not (Test-Path $UvExe)) {
    Write-Error "bin\uv.exe not found in bundle. Bundle is corrupt."
    exit 1
}

$SourceDir = Join-Path $BundleRoot "source"
if (-not (Test-Path $SourceDir)) {
    Write-Error "source\ directory not found in bundle. Bundle is corrupt."
    exit 1
}

# 1. Sync Python dependencies into source\.venv using the bundled uv.
Write-Host "[1/3] Installing Python dependencies into source\.venv via bundled uv..."
Push-Location $SourceDir
try {
    & $UvExe sync
    if ($LASTEXITCODE -ne 0) { throw "uv sync failed with exit code $LASTEXITCODE" }
} finally {
    Pop-Location
}
Write-Host "      done."
Write-Host ""

# 2. Write .env with bundle-absolute paths.
$MemoryDb      = Join-Path $BundleRoot "data\memory.db"
$ExtensionsDir = Join-Path $BundleRoot "data\extensions"
# Pick the first .gguf file inside data\models\.
$ModelFile = Get-ChildItem -Path (Join-Path $BundleRoot "data\models") -Filter "*.gguf" | Select-Object -First 1
if (-not $ModelFile) {
    Write-Error "No .gguf file found in data\models. Bundle is corrupt."
    exit 1
}
$ModelPath = $ModelFile.FullName

$EnvPath = Join-Path $SourceDir ".env"
$EnvContent = @"
# Auto-generated by install.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm').
# NOTES_DIR is ignored by server.py (Windows never ingests) — placeholder only.
NOTES_DIR=C:\notes-placeholder
MEMORY_DB=$MemoryDb
EXTENSIONS_DIR=$ExtensionsDir
MODEL_PATH=$ModelPath

MEMORY_VECTOR_WEIGHT=0.5
MEMORY_TEXT_WEIGHT=0.5
MEMORY_MAX_RESULTS=10
MEMORY_MIN_SCORE=0.6
"@

Write-Host "[2/3] Writing $EnvPath..."
Set-Content -Path $EnvPath -Value $EnvContent -Encoding utf8
Write-Host "      done."
Write-Host ""

# 3. Register the MCP server in Claude Desktop's config.
Write-Host "[3/3] Registering MCP server in %APPDATA%\Claude\claude_desktop_config.json..."
Push-Location $SourceDir
try {
    & $UvExe run python -m setup.install_claude_desktop --uv "$UvExe" --project-dir "$SourceDir"
    if ($LASTEXITCODE -ne 0) { throw "install_claude_desktop failed with exit code $LASTEXITCODE" }
} finally {
    Pop-Location
}
Write-Host ""
Write-Host "Installation complete. Restart Claude Desktop to load the MCP server."
"""

INSTALL_BAT = r"""@echo off
rem install.bat - double-clickable wrapper around install.ps1.
rem Uses -ExecutionPolicy Bypass so the user doesn't need to change system policy.
powershell.exe -ExecutionPolicy Bypass -NoProfile -File "%~dp0install.ps1"
pause
"""

README_WINDOWS = """# local-rag — Windows bundle

This bundle contains everything you need to run the RAG MCP server on Windows:

- `source/` — project code (`server.py`, `ingest.py`, `setup/`, `pyproject.toml`, `uv.lock`)
- `data/memory.db` — pre-built index of the notes (built on the Mac side)
- `data/models/*.gguf` — local embedding model (~603 MB)
- `data/extensions/vector.dll` + `memory.dll` — SQLite extensions for Windows x64
- `bin/uv.exe` — portable [uv](https://github.com/astral-sh/uv) (no system install)
- `install.ps1` + `install.bat` — one-click installer
- `manifest.json` — SHA256 of every bundled file

## Prerequisites

- Windows 10/11 x64.
- Claude Desktop installed.
- ~1.5 GB free disk space.
- No admin rights needed.

## Install (one-time)

1. Unzip this bundle anywhere you like (e.g. `C:\\Users\\<you>\\rag-bundle\\`). Keep the folder — the installer writes paths that point inside it.
2. Double-click `install.bat`.
3. The installer will:
   - Run `uv sync` inside `source\\` to create a local `.venv` with FastMCP + deps.
   - Write `source\\.env` with bundle-absolute paths.
   - Merge a `local-rag` entry into `%APPDATA%\\Claude\\claude_desktop_config.json`
     (creating the file if missing, backing up any existing one to `.bak`).
4. Restart Claude Desktop.

In a conversation, the `search_memory` tool should now appear among available tools.

## Re-indexing

The bundled `memory.db` is a frozen snapshot from the Mac. To refresh the
notes, re-run `ingest.py` on the Mac, rebuild a new bundle with
`scripts/make_bundle.py`, and replace the old `data/memory.db` + (only if the
model changed) `data/models/*.gguf` on Windows.

## Moving the bundle

Paths in `source/.env` are absolute. If you move the bundle folder, re-run
`install.bat` so it regenerates `.env` and the config snippet with the new
location.

## Troubleshooting

- **Claude Desktop doesn't show the tool.** Check `%APPDATA%\\Claude\\logs\\`
  for MCP server errors. The `command` in `claude_desktop_config.json` must be
  the absolute path to `bin\\uv.exe` inside the bundle.
- **`load_extension is not allowed`.** Shouldn't happen with the bundled uv
  (it ships a Python built with extension loading). If it does, please report.
- **`sqlite_memory.dll is not a valid SQLite extension`.** Bundle is corrupt.
  Check `manifest.json` against actual file hashes.
"""


