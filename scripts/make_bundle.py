# Helpers.
# ---------------------------------------------------------------------------


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fp:
        for chunk in iter(lambda: fp.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _extract_from_tar_gz(archive: Path, suffix: str, out_path: Path) -> None:
    """Extract the first *suffix file from a tar.gz into out_path."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive, "r:gz") as tar:
        candidates = [m for m in tar.getmembers() if m.isfile() and m.name.lower().endswith(suffix)]
        if not candidates:
            names = ", ".join(m.name for m in tar.getmembers())
            raise RuntimeError(f"No *{suffix} in {archive.name}. Contents: {names}")
        member = min(candidates, key=lambda m: len(m.name))
        with tar.extractfile(member) as src, open(out_path, "wb") as dst:
            if src is None:
                raise RuntimeError(f"Failed to read {member.name} from {archive.name}")
            while True:
                buf = src.read(65536)
                if not buf:
                    break
                dst.write(buf)


def _extract_uv_exe(archive: Path, out_path: Path) -> None:
    """Pull uv.exe out of the Astral Windows zip."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as zf:
        candidates = [n for n in zf.namelist() if n.lower().endswith("uv.exe")]
        if not candidates:
            raise RuntimeError(f"uv.exe not found in {archive.name}. Contents: {zf.namelist()}")
        # Prefer the shortest-path entry (usually top-level uv.exe, not uvx.exe or a nested copy).
        member = min(candidates, key=len)
        with zf.open(member) as src, open(out_path, "wb") as dst:
            shutil.copyfileobj(src, dst)


# Text suffixes get DEFLATE compression; the rest stays STORED (already compressed).
_TEXT_SUFFIXES = {".py", ".toml", ".lock", ".md", ".json", ".ps1", ".bat", ".example", ".txt", ".cfg", ".ini"}


def _compression_for(name: str) -> int:
    if Path(name).suffix.lower() in _TEXT_SUFFIXES:
        return zipfile.ZIP_DEFLATED
    return zipfile.ZIP_STORED


